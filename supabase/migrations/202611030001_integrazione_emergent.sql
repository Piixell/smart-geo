-- Nessun SECURITY DEFINER: le funzioni rispettano la sessione e RLS del chiamante.
CREATE OR REPLACE FUNCTION public.allinea_spesa_automatica(
  p_user_id uuid, p_descrizione text, p_importo numeric, p_scadenza date,
  p_solo_creazione boolean DEFAULT false, p_maternita numeric DEFAULT NULL
) RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $funzione$
DECLARE voce public.scadenze%ROWTYPE; quante integer;
BEGIN
  IF auth.uid() IS NULL OR auth.uid() IS DISTINCT FROM p_user_id THEN
    RAISE EXCEPTION 'Sessione non valida' USING ERRCODE = '42501';
  END IF;
  IF p_importo IS NULL OR p_importo < 0 OR p_importo::text IN ('NaN','Infinity','-Infinity') THEN
    RAISE EXCEPTION 'Importo non valido';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended(p_user_id::text || ':' || p_descrizione, 0));
  SELECT count(*) INTO quante FROM public.scadenze WHERE user_id = p_user_id AND descrizione = p_descrizione;
  -- I doppioni richiedono revisione: non cancellare righe né dati di pagamento.
  IF quante > 1 THEN RETURN; END IF;
  IF quante = 1 THEN
    SELECT * INTO voce FROM public.scadenze WHERE user_id = p_user_id AND descrizione = p_descrizione FOR UPDATE;
    IF voce.pagamento OR p_solo_creazione THEN RETURN; END IF;
    UPDATE public.scadenze SET spese = p_importo, data_scadenza = coalesce(data_scadenza, p_scadenza)
    WHERE id = voce.id AND user_id = p_user_id;
  ELSIF p_importo > 0 OR p_solo_creazione THEN
    INSERT INTO public.scadenze(user_id, descrizione, spese, data_scadenza, categoria, pagamento, pagamento_pronto, maternita)
    VALUES(p_user_id, p_descrizione, p_importo, p_scadenza, 'variabili', false, false, p_maternita);
  END IF;
END;
$funzione$;

CREATE OR REPLACE FUNCTION public.riproponi_costi_fissi(p_user_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $funzione$
DECLARE primo_anno integer; anno integer; ultimo_anno integer := extract(year FROM current_date)::integer + 1;
BEGIN
  IF auth.uid() IS NULL OR auth.uid() IS DISTINCT FROM p_user_id THEN
    RAISE EXCEPTION 'Sessione non valida' USING ERRCODE = '42501';
  END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended(p_user_id::text || ':costi-fissi', 0));
  SELECT min(extract(year FROM coalesce(data_scadenza::date, created_at::date)))::integer INTO primo_anno
  FROM public.scadenze WHERE user_id = p_user_id;
  IF primo_anno IS NULL THEN RETURN; END IF;
  FOR anno IN greatest(primo_anno + 1, 1900)..ultimo_anno LOOP
    INSERT INTO public.scadenze(user_id, descrizione, spese, data_scadenza, categoria, pagamento, pagamento_pronto, data_pagamento)
    SELECT DISTINCT ON (lower(btrim(s.descrizione))) p_user_id, s.descrizione, s.spese,
      coalesce((s.data_scadenza::date + interval '1 year')::date, make_date(anno, 12, 31)),
      'fissi', false, false, NULL
    FROM public.scadenze s
    WHERE s.user_id = p_user_id
      AND extract(year FROM coalesce(s.data_scadenza::date, s.created_at::date)) = anno - 1
      AND (s.categoria = 'fissi' OR (s.categoria IS NULL AND lower(s.descrizione) !~ 'tasse|contributo integrativo|contributo soggettivo'))
      AND NOT EXISTS (SELECT 1 FROM public.scadenze d WHERE d.user_id = p_user_id
        AND lower(btrim(d.descrizione)) = lower(btrim(s.descrizione))
        AND extract(year FROM coalesce(d.data_scadenza::date, d.created_at::date)) = anno)
    ORDER BY lower(btrim(s.descrizione)), s.id DESC;
  END LOOP;
END;
$funzione$;

