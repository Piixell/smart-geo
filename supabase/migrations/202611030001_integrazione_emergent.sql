CREATE OR REPLACE FUNCTION public.aggiorna_data_stato_emergent()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $funzione$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.stato_modificato_at := coalesce(NEW.stato_modificato_at, now());
  ELSIF to_jsonb(NEW)->TG_ARGV[0] IS DISTINCT FROM to_jsonb(OLD)->TG_ARGV[0] THEN
    NEW.stato_modificato_at := now();
  ELSE
    NEW.stato_modificato_at := OLD.stato_modificato_at;
  END IF;
  RETURN NEW;
END;
$funzione$;
