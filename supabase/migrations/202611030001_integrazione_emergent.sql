    EXECUTE format('DROP POLICY IF EXISTS emergent_solo_proprietario ON public.%I', tabella);
    EXECUTE format('CREATE POLICY emergent_solo_proprietario ON public.%I AS RESTRICTIVE FOR ALL TO authenticated USING ((SELECT auth.uid()) = user_id) WITH CHECK ((SELECT auth.uid()) = user_id)', tabella);
    EXECUTE format('DROP POLICY IF EXISTS emergent_accesso_proprietario ON public.%I', tabella);
    EXECUTE format('CREATE POLICY emergent_accesso_proprietario ON public.%I FOR ALL TO authenticated USING ((SELECT auth.uid()) = user_id) WITH CHECK ((SELECT auth.uid()) = user_id)', tabella);
    sequenza := NULL;
    IF EXISTS (SELECT 1 FROM information_schema.columns c WHERE c.table_schema = 'public' AND c.table_name = tabella AND c.column_name = 'id') THEN
      sequenza := pg_get_serial_sequence(format('public.%I', tabella), 'id');
    END IF;
    IF sequenza IS NOT NULL THEN
      EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC, anon', sequenza);
      EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated', sequenza);
    END IF;
  END LOOP;
END;
$sicurezza$;

